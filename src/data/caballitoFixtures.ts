export function buildGoogleStreetViewUrl(
  coordinates: [number, number],
  heading = 180
): string {
  const [lng, lat] = coordinates;
  return `https://www.google.com/maps/@?api=1&map_action=pano&viewpoint=${lat.toFixed(6)},${lng.toFixed(6)}&heading=${heading}&pitch=5&fov=85`;
}

