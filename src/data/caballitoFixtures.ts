function closeRing(vertices: [number, number][]): [number, number][] {
  if (vertices.length === 0) return [];
  const first = vertices[0];
  const last = vertices[vertices.length - 1];
  if (first[0] === last[0] && first[1] === last[1]) {
    return vertices;
  }
  return [...vertices, [first[0], first[1]]];
}

export function buildZonesForVariant(
  variant: ZoneVariantId = 'ARANGUREN_COMPLETA',
  customZonaARing?: [number, number][]
): ZoneDefinition[] {
  const activeVertices =
    variant === 'ARANGUREN_COMPLETA'
      ? ZONA_A_VERTICES_ARANGUREN
      : ZONA_A_VERTICES_RIVADAVIA_SUR;

  const zonaARing = closeRing(
    customZonaARing && customZonaARing.length >= 3
      ? customZonaARing
      : activeVertices.map((v) => v.coordinates)
  );

  const zonaBOuterRing = closeRing(
    ZONA_B_OUTER_VERTICES.map((v) => v.coordinates)
  );

  const zonaA: ZoneDefinition = {
    id: 'zona-a',
    name:
      variant === 'ARANGUREN_COMPLETA'
        ? 'Zona A — Prioritaria (Aranguren a Eva Perón · Continuidad Validada USIG)'
        : 'Zona A — Prioritaria (Variante Estricta Rivadavia a Eva Perón)',
    zoneType: 'ZONA_A',
    priority: 1,
    validationStatus: 'PARCIAL_CON_OBSERVACIONES',
    boundaryNotes:
      variant === 'ARANGUREN_COMPLETA'
        ? 'Incluye empalme norte sobre vías del FFCC Sarmiento por Nicasio Oroño (cont. Malvinas Argentinas) y Dr. Nicolás Repetto / F. García Lorca (cont. Emilio Mitre) hasta Dr. Juan F. Aranguren.'
        : 'Restringida al sur de Av. Rivadavia donde las arterias conservan el nombre Emilio Mitre y Malvinas Argentinas.',
    nominalLimits: {
      north: 'Dr. Juan Felipe Aranguren (vía N. Oroño / Dr. N. Repetto)',
      south: 'Av. Eva Perón',
      east: 'Emilio Mitre (y cont. norte Dr. Nicolás Repetto)',
      west: 'Malvinas Argentinas (y cont. norte Nicasio Oroño)',
    },
    outerRing: zonaARing,
    verifiedVertices: activeVertices,
    isSynthetic: true,
  };

  // Zona B se deriva geométricamente como diferencia: Perímetro General menos Zona A (anillo interior)
  const zonaB: ZoneDefinition = {
    id: 'zona-b',
    name: 'Zona B — Secundaria (Perímetro General menos Zona A · Sin Superposición)',
    zoneType: 'ZONA_B',
    priority: 2,
    validationStatus: 'PARCIAL_CON_OBSERVACIONES',
    boundaryNotes:
      'Calculada como diferencia geométrica (Perímetro General − Zona A). Al oeste Donato Álvarez continúa como Curapaligue al sur de Rivadavia; al este Acoyte continúa como Av. José María Moreno; al sur cierra en Saraza (2ª cuadra paralela al sur de Av. Asamblea).',
    nominalLimits: {
      north: 'Av. Gaona / Empalme Av. Díaz Vélez (Cid Campeador)',
      south: 'Saraza (2 cuadras al sur de Av. Asamblea)',
      east: 'Av. Acoyte → Av. José María Moreno',
      west: 'Tte. Gral. Donato Álvarez → Curapaligue',
    },
    outerRing: zonaBOuterRing,
    holes: [zonaARing],
    verifiedVertices: ZONA_B_OUTER_VERTICES,
    isSynthetic: true,
  };

  return [zonaA, zonaB];
}

